/**
 * Bundle the edge (esbuild) from the frontend's own modules:
 *
 *   edge/dist/mcp-engine.mjs  createMcpEngine(files, hooks): the docs MCP route + engine, one
 *                             instance per site, reading a content snapshot through the fs shim
 *   edge/dist/worker.mjs      the Cloudflare Worker (wrangler.toml main)
 *   edge/dist/handler.mjs     the same handler for Node (server/server.mjs)
 *
 * `@/…` resolves into frontend/src exactly as in the Next app, so routing (docs/host.ts), the geo
 * route and the MCP server are the engine's code, not copies.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const FRONTEND = path.resolve(ROOT, "..", "frontend");
const OUT = path.join(ROOT, "edge", "dist");

const EXTS = ["", ".ts", ".tsx", ".mjs", ".js", "/index.ts", "/index.tsx", "/index.js"];

function resolvePlugin({ shims }) {
  return {
    name: "markdrop-docs-resolve",
    setup(b) {
      b.onResolve({ filter: /^@\// }, (args) => {
        const base = path.join(FRONTEND, "src", args.path.slice(2));
        for (const ext of EXTS) {
          const p = base + ext;
          if (fs.existsSync(p) && fs.statSync(p).isFile()) return { path: p };
        }
        return { errors: [{ text: `cannot resolve ${args.path}` }] };
      });
      if (shims) {
        const shim = (f) => ({ path: path.join(ROOT, "edge", "shims", f) });
        b.onResolve({ filter: /^(node:)?fs$/ }, () => shim("fs.mjs"));
        b.onResolve({ filter: /^(node:)?path$/ }, () => shim("path.mjs"));
        b.onResolve({ filter: /^next\/server$/ }, () => shim("next-server.mjs"));
      }
    },
  };
}

const common = {
  bundle: true,
  logLevel: "warning",
  nodePaths: [path.join(FRONTEND, "node_modules")],
  mainFields: ["module", "main"],
  conditions: ["import", "module", "default"],
  jsx: "automatic",
  target: "es2022",
  legalComments: "none",
  // The docs host settings are read at module load (host.ts, hosts.ts); the edge decides hosts
  // from the store instead, so they are empty here.
  define: {
    "process.env.NEXT_PUBLIC_DOCS_HOST": '""',
    "process.env.NEXT_PUBLIC_DOCS_HOSTS": '""',
    "process.env.NEXT_PUBLIC_PRIMARY_HOSTS": '""',
    "process.env.NEXT_PUBLIC_API_URL": '""',
  },
};

export async function bundle() {
  fs.mkdirSync(OUT, { recursive: true });
  // 1. The MCP engine, wrapped so each site gets its own module instance over its own files.
  const eng = await esbuild.build({
    ...common,
    entryPoints: [path.join(ROOT, "edge", "mcp-entry.mjs")],
    format: "iife",
    globalName: "__engine",
    platform: "neutral",
    write: false,
    plugins: [resolvePlugin({ shims: true })],
    define: { ...common.define, "process.env.NODE_ENV": '"production"', "process.env.DOCS_CONTENT_DIR": '"/site"' },
  });
  const code = eng.outputFiles[0].text;
  const wrapped = `// Generated by builder/bundle.mjs from frontend/src (docs MCP route + engine). Do not edit.
export function createMcpEngine(__siteFiles, __hooks) {
  const process = { env: { NODE_ENV: "production", DOCS_CONTENT_DIR: "/site" }, cwd: () => "/" };
${code}
  return __engine;
}
`;
  fs.writeFileSync(path.join(OUT, "mcp-engine.mjs"), wrapped);

  // 2. The Worker and the Node handler.
  const worker = await esbuild.build({
    ...common,
    entryPoints: [path.join(ROOT, "edge", "worker.mjs")],
    outfile: path.join(OUT, "worker.mjs"),
    format: "esm",
    platform: "neutral",
    plugins: [resolvePlugin({ shims: false })],
    metafile: true,
  });
  await esbuild.build({
    ...common,
    entryPoints: [path.join(ROOT, "edge", "handler.mjs")],
    outfile: path.join(OUT, "handler.mjs"),
    format: "esm",
    platform: "node",
    plugins: [resolvePlugin({ shims: false })],
  });
  const size = (f) => fs.statSync(path.join(OUT, f)).size;
  return { mcpEngine: size("mcp-engine.mjs"), worker: size("worker.mjs"), handler: size("handler.mjs"), workerInputs: Object.keys(worker.metafile.inputs).length };
}
