test("the folder on disk: pages with front matter, site.json, assets, report, origins (what the runner reads)", async () => {
  const r = await run("mintlify-mintjson");
  const out = tmp();
  writeOutput(r, out);
  const files = [];
  const walk = (d, rel = "") => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(path.join(d, e.name), p);
      else files.push(p);
    }
  };
  walk(out);
  assert.deepEqual(files.sort(), [
    "_IMPORT_REPORT.md", "_import-report.json", "_origins.json", "api-ref/introduction.md", "api-ref/users/get.md", "essentials/settings.md", "index.md",
    "public/docs-assets/import/favicon@1x.png", "public/docs-assets/import/images/hero@1x.png", "public/docs-assets/import/logo/light@1x.png",
    "quickstart.md", "redirects.json", "site.json", "videos.json",
  ]);
  const q = splitFrontMatter(fs.readFileSync(path.join(out, "quickstart.md"), "utf8"));
  assert.deepEqual(q.fm, { title: "Quickstart", nav: "Start here", description: "Send your first widget in five minutes.", updated: "2026-11-02" });
  assert.equal(sniffExt(fs.readFileSync(path.join(out, "public/docs-assets/import/logo/light@1x.png"))), "png");
  const report = JSON.parse(fs.readFileSync(path.join(out, "_import-report.json"), "utf8"));
  assert.equal(report.format, "markdrop-docs-import/1");
  assert.deepEqual(report.openapi, [{ path: "openapi.yaml", from: "mint.json" }]);
  assert.deepEqual(Object.keys(report.counts).filter((k) => ["pages", "groups", "images", "files", "notes", "brokenLinks", "missing", "keptOriginal", "redirects", "hidden"].includes(k)).length, 10);
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(out, "_origins.json"), "utf8")), r.origins);
  assert.throws(() => writeOutput(r, path.join(HERE, "..", "..", "..")), /looks like a project folder/);
  fs.rmSync(out, { recursive: true, force: true });
});

test("CLI: progress lines, a folder without pages fails clearly, the repo itself is refused", () => {
  const cli = path.join(HERE, "..", "github.mjs");
  const out = tmp();
  const ok = spawnSync(process.execPath, [cli, "--dir", path.join(FIX, "mkdocs"), "--path", "", "--out", out, "--id", "import", "--repo", "acme/docs", "--ref", SHA, "--date", "2026-11-02"], { encoding: "utf8" });
  assert.equal(ok.status, 0, ok.stderr);
  const lines = ok.stdout.split("\n");
  assert.ok(lines.includes("pages: 5"));
  assert.ok(lines.includes("progress: pages 5/5"));
  assert.ok(lines.includes("progress: assets 1/1"));
  assert.ok(lines.some((l) => l.startsWith("done: 5 pages")));
  const empty = spawnSync(process.execPath, [cli, "--dir", path.join(FIX, "mkdocs"), "--path", "docs/assets", "--out", out, "--format", "markdown"], { encoding: "utf8" });
  assert.equal(empty.status, 1);
  assert.match(empty.stderr, /no pages: docs\/assets has no \.md or \.mdx files/);
  const inRepo = spawnSync(process.execPath, [cli, "--dir", path.join(FIX, "mkdocs"), "--out", path.join(HERE, "tmp-out")], { encoding: "utf8" });
  assert.equal(inRepo.status, 2);
  assert.match(inRepo.stderr, /refusing to write into the repository/);
  fs.rmSync(out, { recursive: true, force: true });
});
