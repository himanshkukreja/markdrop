/**
 * The GitHub import end to end on fictional fixture repos (test/fixtures/github/<name>): detection,
 * pages, nav, tabs, redirects, assets, directives, report, origins, OpenAPI candidates, and the
 * folder written to disk. No network, no child processes except the two CLI checks at the end.
 *   npm run docs:test
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { convertRepo, writeOutput, readRepoDir, detectFormat, inspectFolders, suggestFolders, splitFrontMatter } from "../github.mjs";
import { sniffExt } from "../lib/guard.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const FIX = path.join(HERE, "fixtures", "github");
const SHA = "0123456789abcdef0123456789abcdef01234567";
const OPTS = { repo: "acme/docs", ref: SHA, branch: "main", date: "2026-11-02" };
const run = (name, extra = {}) => convertRepo({ dir: path.join(FIX, name), ...OPTS, ...extra });
const page = (r, p) => r.pages.find((x) => x.path === p);
const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), "gh-import-"));

test("each fixture's format, content root and suggested folders", () => {
  const want = {
    "markdown-folder": ["markdown", ""],
    "gitbook-sync": ["gitbook", "docs"],
    "mintlify-mintjson": ["mintlify", ""],
    "mintlify-docsjson": ["mintlify", ""],
    "docusaurus-object-sidebar": ["docusaurus", "docs"],
    "docusaurus-autogenerated": ["docusaurus", "content"],
    mkdocs: ["mkdocs", "docs"],
  };
  for (const [name, [format, root]] of Object.entries(want)) {
    const src = readRepoDir(path.join(FIX, name));
    const det = detectFormat(src.files, src.readText, "");
    assert.equal(det.format, format, name);
    assert.equal(det.contentRoot, root, name);
    assert.equal(suggestFolders(src.files, src.readText)[0], "", name);
  }
  const md = readRepoDir(path.join(FIX, "markdown-folder"));
  assert.deepEqual(inspectFolders(md.files, md.readText), [{ path: "", format: "markdown", pages: 8 }]);
  const mk = readRepoDir(path.join(FIX, "mkdocs"));
  assert.deepEqual(suggestFolders(mk.files, mk.readText), ["", "docs"]);
});

