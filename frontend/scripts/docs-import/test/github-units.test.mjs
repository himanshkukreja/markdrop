test("SUMMARY.md, docs.json sections, Docusaurus ids and addresses", () => {
  assert.deepEqual(parseSummary("# Table of contents\n\n* [A](a.md)\n  * [B](b/README.md)\n\n## Group <a href=\"#g\" id=\"g\"></a>\n\n- [C](c.md)\n"), [
    { group: "", items: [{ title: "A", href: "a.md", depth: 0 }, { title: "B", href: "b/README.md", depth: 1 }] },
    { group: "Group", items: [{ title: "C", href: "c.md", depth: 0 }] },
  ]);
  const nav = docsJsonNav({
    versions: [
      { version: "v2", anchors: [{ anchor: "Docs", groups: [{ group: "G", root: "g/index", pages: ["a", { group: "Nested", pages: ["b", { page: "c" }] }, { page: "secret", hidden: true }, { title: "Status", href: "https://status.example.com" }] }] }, { anchor: "Out", href: "https://example.com" }] },
      { version: "v1", groups: [{ group: "Old", pages: ["v1/a"] }] },
    ],
    global: { anchors: [{ anchor: "Blog", href: "https://example.com/blog" }] },
  });
  assert.deepEqual(nav.sections.map((s) => ({ label: s.label, groups: s.groups.map((g) => [g.group, g.refs, g.hiddenRefs]) })), [{ label: "Docs", groups: [["G", ["g/index", "a", "b", "c"], ["secret"]]] }]);
  assert.deepEqual(nav.links.map((l) => l.href).sort(), ["https://example.com", "https://example.com/blog", "https://status.example.com"]);
  assert.deepEqual(nav.others, ["v1/a"]);
  assert.equal(docsJsonSections({ groups: [{ group: "X", pages: ["x"] }] })[0].groups[0].group, "X");
  assert.deepEqual(resolveRefs({ redirects: { $ref: "./r.json" }, nav: { $ref: "../outside.json" } }, { from: "site/docs.json", root: "site", readText: (p) => (p === "site/r.json" ? '[{"source":"/a","destination":"/b"}]' : null) }), { redirects: [{ source: "/a", destination: "/b" }], nav: {} });
  const ig = mintignore("# drafts\ndrafts/\n*.draft.mdx\n/private\n");
  assert.deepEqual(["drafts/x.mdx", "a/drafts/y.mdx", "guide.draft.mdx", "private/z.mdx", "a/private/z.mdx", "guide.mdx"].filter(ig), ["drafts/x.mdx", "a/drafts/y.mdx", "guide.draft.mdx", "private/z.mdx"]);
  assert.equal(docId("01-guides/02-setup.md", {}), "guides/setup");
  assert.equal(docId("guides/x.md", { id: "custom" }), "guides/custom");
  assert.deepEqual(docUrlSegments("guides/x.md", { slug: "/start" }), ["start"]);
  assert.deepEqual(docUrlSegments("guides/x.md", { slug: "rel" }), ["guides", "rel"]);
  assert.deepEqual(docUrlSegments("guides/guides.md", {}), ["guides"]);
});

