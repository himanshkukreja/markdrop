test("JS literal: comments, unquoted keys, single quotes, trailing commas, template strings", () => {
  const v = parseJsLiteral(`{
    // a comment
    docs: ['intro', {type: 'doc', id: "guides/a", label: \`A guide\`,},], /* block */
    'quoted-key': [1, -2.5, 0x10, true, false, null,],
  }`);
  assert.deepEqual(v, { docs: ["intro", { type: "doc", id: "guides/a", label: "A guide" }], "quoted-key": [1, -2.5, 16, true, false, null] });
  assert.equal(parseJsLiteral(`{a: 'it\\'s'} as const;`).a, "it's");
});

test("JS literal: code is refused, never run", () => {
  for (const bad of [
    "{ docs: require('./x') }",
    "{ ...base }",
    "{ docs: items }",
    "{ docs: () => [] }",
    "{ [key]: 1 }",
    "{ docs: `a ${b}` }",
    "{ docs() { return [] } }",
    "{ a: 1 } + 2",
  ])
    assert.throws(() => parseJsLiteral(bad), JsLiteralError, bad);
});

test("sidebars files: module.exports, export default, a typed const, JSON; code → an error to fall back on", () => {
  assert.deepEqual(parseSidebarsFile("module.exports = { docs: ['a'] };"), { docs: ["a"] });
  assert.deepEqual(parseSidebarsFile("export default { docs: ['a'] } satisfies X;"), { docs: ["a"] });
  assert.deepEqual(parseSidebarsFile("import type {SidebarsConfig} from 'x';\nconst sidebars: SidebarsConfig = { s: [{type: 'autogenerated', dirName: '.'}] };\nexport default sidebars;"), { s: [{ type: "autogenerated", dirName: "." }] });
  assert.deepEqual(parseSidebarsFile('{"docs": ["a"]}', "sidebars.json"), { docs: ["a"] });
  assert.throws(() => parseSidebarsFile("module.exports = { docs: require('./generated') };"), JsLiteralError);
  assert.throws(() => parseSidebarsFile("module.exports = makeSidebars();"), JsLiteralError);
});

