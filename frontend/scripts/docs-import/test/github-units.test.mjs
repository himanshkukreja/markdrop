test("detection: first match wins, content roots from the configs", () => {
  const files = new Map([
    ["site/docs.json", '{"navigation": {"pages": ["index"]}}'],
    ["site/index.mdx", ""],
    ["other/docs.json", '{"not": "mintlify"}'],
    ["other/README.md", ""],
    ["book/.gitbook.yaml", "root: ./content/"],
    ["book/content/README.md", ""],
    ["py/mkdocs.yml", "docs_dir: pages\n"],
    ["py/pages/index.md", ""],
    ["web/docusaurus.config.js", "module.exports = { presets: [['classic', { docs: { path: 'guides' } }]] }"],
    ["web/guides/intro.md", ""],
    ["web/guides/_partial.md", ""],
    ["node_modules/pkg/docs.json", '{"navigation": {}}'],
    ["build/mkdocs.yml", ""],
  ]);
  const read = (p) => files.get(p) ?? null;
  const paths = [...files.keys()];
  assert.deepEqual(detectFormat(paths, read, "site"), { format: "mintlify", folder: "site", contentRoot: "site", config: "site/docs.json" });
  assert.equal(detectFormat(paths, read, "other").format, "markdown");
  assert.equal(detectFormat(paths, read, "book").contentRoot, "book/content");
  assert.equal(detectFormat(paths, read, "py").contentRoot, "py/pages");
  const web = detectFormat(paths, read, "web");
  assert.equal(web.contentRoot, "web/guides");
  assert.deepEqual(listPages(paths, web), ["web/guides/intro.md"]);
  assert.equal(detectFormat(paths, read, "site", "markdown").format, "markdown");
  assert.deepEqual(suggestFolders(paths, read), ["site", "py", "web", ""]);
});

