  assert.equal(pagePath(["a", "b", "c", "d", "e", "f", "g"]), "/a/b/c/d/e/f-g");
  const used = new Set();
  assert.deepEqual([uniquePath("/x", used), uniquePath("/x", used)], ["/x", "/x-2"]);
