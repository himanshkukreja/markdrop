test("asset names: every segment the runner accepts, 8 segments at most, unique", () => {
  const taken = new Set();
  const rel = assetRel(".gitbook/assets/My Screenshot (1).png", "png", { taken });
  assert.equal(rel, "import/gitbook/assets/My-Screenshot-1-.png");
  assert.equal(assetRel(".gitbook/assets/My Screenshot (1).png", "png", { taken }), "import/gitbook/assets/My-Screenshot-1--2.png");
  const deep = assetRel("a/b/c/d/e/f/g/h/i.png", "png", { taken, suffix: "@1x" });
  assert.ok(deep.split("/").length <= 8, deep);
  for (const r of [rel, deep, assetRel("-x/_y/.z.jpeg", "jpeg", { taken })]) assert.ok(r.split("/").every((s) => SAFE_SEGMENT.test(s)), r);
});

