/* ── tar ─────────────────────────────────────────────────────────────────── */

test("tar: GitHub's folder stripped, the commit from the pax global header, only kept files read", async () => {
  const sha = "fedcba9876543210fedcba9876543210fedcba98";
  const tgz = githubTarball({ "README.md": "# Acme\n", "docs/a.md": "A", "src/app.js": "x" }, { sha });
  const res = await readTarGz(tgz, { keep: (p) => p.endsWith(".md") });
  assert.equal(res.commit, sha);
  assert.deepEqual([...res.map.keys()].sort(), ["README.md", "docs/a.md"]);
  assert.equal(res.map.get("docs/a.md").toString(), "A");
  assert.equal(res.skipped, 1);
});

test("tar: symlinks, hard links, devices, .., absolute and NUL names are refused", async () => {
  const tgz = makeTarGz([
    { name: "top/ok.md", body: "ok" },
    { name: "top/link.md", type: "2", linkname: "/etc/passwd" },
    { name: "top/hard.md", type: "1", linkname: "top/ok.md" },
    { name: "top/dev", type: "3" },
    { name: "top/../../escape.md", body: "x" },
    { name: "/abs/path.md", body: "x" },
    { name: "x", type: "x", body: paxBody({ path: "top/nul\0name.md" }) },
    { name: "top/placeholder", body: "x" },
  ]);
  const res = await readTarGz(tgz);
  assert.deepEqual([...res.map.keys()], ["ok.md"]);
  assert.deepEqual(res.refused.map((r) => r.reason), ["symlink", "hard link", "character device", "a .. segment", "absolute path", "NUL byte in the name"]);
  assert.deepEqual(cleanTarPath("a/./b//c.md"), { path: "b/c.md" });
});

test("tar: caps on files, total bytes and per-file size; garbage is not a tar", async () => {
  const files = Object.fromEntries(Array.from({ length: 5 }, (_, i) => [`p${i}.md`, "x".repeat(100)]));
  await assert.rejects(readTarGz(githubTarball(files), { limits: { maxFiles: 3 } }), /more than 3 files/);
  await assert.rejects(readTarGz(githubTarball(files), { limits: { maxBytes: 250 } }), TarError);
  const big = await readTarGz(githubTarball({ "big.png": "x".repeat(2000), "small.md": "s" }), { limits: { maxFileBytes: 1000 } });
  assert.deepEqual([...big.map.keys()], ["small.md"]);
  assert.match(big.refused[0].reason, /larger than/);
  await assert.rejects(readTarGz(zlib.gzipSync(Buffer.from("not a tar at all, just text".repeat(40)))), /not a tar archive/);
  await assert.rejects(readTarGz(Buffer.from("not gzip")), /not a readable/);
});

