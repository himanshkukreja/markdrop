// Cloudflare build only (scripts/cf/build.sh, before `opennextjs-cloudflare build`): a Worker has no
// disk, so the docs content the server reads at request time (src/docs/content.ts: the MCP server,
// the docs 404, dynamic docs pages; src/docs/media.ts: chapter VTT files) is snapshotted into a
// module. next.config.ts aliases src/docs/contentSnapshot to it when MARKDROP_CF_BUILD=1; Vercel
// builds keep the empty stub and read the disk as before (src/docs/contentFs.ts).
//
// Keys are paths relative to the frontend folder (process.cwd() at build time; "/" on the Worker,
// where content.ts's CONTENT_DIR becomes /content/docs and maps back to the same keys).
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const OUT = path.join(ROOT, ".cf", "docs-snapshot.mjs");
const TEXT = /\.(md|json|ya?ml|txt|html|css|js|mjs|vtt)$/i;
const MAX_FILE = 4 * 1024 * 1024;

const files = {};
let bytes = 0;
function walk(rel, keep) {
  let entries = [];
  try {
    entries = fs.readdirSync(path.join(ROOT, rel), { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const r = `${rel}/${e.name}`;
    if (e.isDirectory()) {
      if (e.name !== "node_modules") walk(r, keep);
    } else if (e.isFile() && keep(e.name)) {
      const st = fs.statSync(path.join(ROOT, r));
      if (st.size > MAX_FILE) throw new Error(`docs-snapshot: ${r} is ${st.size} bytes; too big for the Worker bundle`);
      files[r] = fs.readFileSync(path.join(ROOT, r), "utf8");
      bytes += st.size;
    }
  }
}
// The docs content folder (pages, site.json, changelog, OpenAPI, media manifest, embeds).
walk("content/docs", (n) => TEXT.test(n));
// Chapter files under the app's public/ that media.ts reads with fs (the rest of public/ is ASSETS).
walk("public/docs-assets", (n) => /\.vtt$/i.test(n));

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `// Generated by scripts/cf/docs-snapshot.mjs. Do not edit.\nconst files = ${JSON.stringify(files)};\nexport default files;\n`);
console.log(`docs-snapshot: ${Object.keys(files).length} files, ${(bytes / 1024).toFixed(0)} KiB -> ${path.relative(ROOT, OUT)}`);
